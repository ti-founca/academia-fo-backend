CREATE TABLE config.refresh_token
(
    id          integer NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    jti         uuid NOT NULL,
    idusuario   integer NOT NULL,
    emitido_en  timestamp with time zone NOT NULL DEFAULT now(),
    expira_en   timestamp with time zone NOT NULL,
    revocado_en timestamp with time zone,
    PRIMARY KEY (id),
    CONSTRAINT uq_refresh_token_jti UNIQUE (jti),
    CONSTRAINT fk_refresh_token_usuario FOREIGN KEY (idusuario)
        REFERENCES config.usuarios (idusuario) MATCH SIMPLE
        ON UPDATE NO ACTION
        ON DELETE CASCADE
);

CREATE INDEX ix_refresh_token_idusuario ON config.refresh_token (idusuario);
